import asyncio
from llm_service import process_message

async def summary_message(old_summary: str, new_message: str) -> str:

    prompt = f"""
    Ты — профессиональный ассистент. Твоя задача — обновить текущее краткое содержание (саммари) диалога, добавив в него смысл из нового сообщения.

    Текущее саммари:
    "{old_summary}"

    Новое сообщение:
    "{new_message}"

    Инструкции:
    1. Интегрируй новый смысл в текущее саммари, сохраняя логику и хронологию.
    2. Если новое сообщение не содержит важной информации (флуд, приветствие, ок), оставь текущее саммари без изменений.
    3. Избегай дублирования информации.
    4. Пиши тезисно, в третьем лице, без лишней воды.

    Ответ должен содержать ТОЛЬКО обновленный текст саммари. Никаких вводных слов вроде "Вот обновленное саммари:" или кавычек.
    """

    result = await process_message(prompt)
    return result


